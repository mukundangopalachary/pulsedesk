/*
# Team management: invites and member role changes

Plain-English summary: lets workspace owners and admins invite teammates by email with a role (admin, member, or viewer), lets them change a member's role or remove them, and gives invited people a link they can use to join the workspace.

## 1. New table
- `workspace_invites`: one row per invitation, with the invited email, the role they will get, a secret token used in the invite link, who invited them, and an expiry (7 days). A row is marked used by filling `accepted_at`.

## 2. New functions (all check the caller's role before doing anything)
- `create_invite(workspace, email, role)`: owners and admins can invite. Returns the secret token for the invite link. Re-inviting the same pending email returns the existing token. Blocked if that person is already a member.
- `accept_invite(token)`: a signed-in user joins the workspace if their account email matches the invite, the invite is unused and not expired. Returns the workspace slug. Cannot be used twice.
- `change_member_role(workspace, member, role)`: owners and admins can change a member's role to admin, member, or viewer. The workspace owner's role cannot be changed, and nobody can change their own role here.
- `remove_member(workspace, member)`: owners and admins can remove a member. The workspace owner cannot be removed, and nobody can remove themselves here.
- `cancel_invite(invite_id)`: owners and admins can delete a pending invite.

## 3. Security
- Row level security is enabled on `workspace_invites`.
- Only owners and admins of a workspace can read its pending invites; nobody can insert, update or delete invites directly — only through the functions above.
- All functions are removed from public access and granted only to signed-in users.

## Important notes
1. Invite tokens are 48-character random hex strings generated by pgcrypto.
2. Invites expire after 7 days; expired or used invites can never be accepted.
3. Removing a member keeps their past internal comments (they stay attributed), and any feedback they were assigned becomes unassigned automatically by the existing foreign key rule.
*/

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.workspace_invites (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  email text NOT NULL CHECK (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
  role text NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  token text NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(24), 'hex'),
  invited_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '7 days',
  accepted_at timestamptz
);

CREATE INDEX IF NOT EXISTS workspace_invites_workspace_idx ON public.workspace_invites (workspace_id, accepted_at);

ALTER TABLE public.workspace_invites ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.workspace_invites TO authenticated;

DROP POLICY IF EXISTS "Admins can view pending invites" ON public.workspace_invites;
CREATE POLICY "Admins can view pending invites"
ON public.workspace_invites FOR SELECT
TO authenticated
USING (public.workspace_role(workspace_id) IN ('owner', 'admin'));

CREATE OR REPLACE FUNCTION public.create_invite(_ws uuid, _email text, _role text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  clean_email text := lower(btrim(_email));
  existing text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in to invite teammates';
  END IF;
  IF public.workspace_role(_ws) NOT IN ('owner', 'admin') THEN
    RAISE EXCEPTION 'Only owners and admins can invite teammates';
  END IF;
  IF _role NOT IN ('admin', 'member', 'viewer') THEN
    RAISE EXCEPTION 'Choose a valid role';
  END IF;
  IF clean_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' THEN
    RAISE EXCEPTION 'Enter a valid email address';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.workspace_members m
    JOIN public.profiles p ON p.id = m.user_id
    WHERE m.workspace_id = _ws AND lower(p.email) = clean_email
  ) THEN
    RAISE EXCEPTION 'This person is already on your team.';
  END IF;

  SELECT token INTO existing
  FROM public.workspace_invites
  WHERE workspace_id = _ws AND lower(email) = clean_email
    AND accepted_at IS NULL AND expires_at > now()
  LIMIT 1;
  IF existing IS NOT NULL THEN
    RETURN existing;
  END IF;

  INSERT INTO public.workspace_invites (workspace_id, email, role)
  VALUES (_ws, clean_email, _role)
  RETURNING token INTO existing;

  RETURN existing;
END;
$$;

CREATE OR REPLACE FUNCTION public.accept_invite(_token text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  inv public.workspace_invites;
  user_email text;
  ws_slug text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in to accept an invitation';
  END IF;

  SELECT * INTO inv FROM public.workspace_invites WHERE token = _token FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This invitation link is not valid.';
  END IF;
  IF inv.accepted_at IS NOT NULL THEN
    RAISE EXCEPTION 'This invitation has already been used.';
  END IF;
  IF inv.expires_at <= now() THEN
    RAISE EXCEPTION 'This invitation has expired. Ask your teammate to send a new one.';
  END IF;

  SELECT lower(email) INTO user_email FROM auth.users WHERE id = auth.uid();
  IF user_email IS NULL OR user_email <> lower(inv.email) THEN
    RAISE EXCEPTION 'This invite was sent to %. Sign in with that email to accept it.', inv.email;
  END IF;

  SELECT slug INTO ws_slug FROM public.workspaces WHERE id = inv.workspace_id;

  IF NOT EXISTS (
    SELECT 1 FROM public.workspace_members
    WHERE workspace_id = inv.workspace_id AND user_id = auth.uid()
  ) THEN
    INSERT INTO public.workspace_members (workspace_id, user_id, role)
    VALUES (inv.workspace_id, auth.uid(), inv.role);
  END IF;

  UPDATE public.workspace_invites SET accepted_at = now() WHERE id = inv.id;

  RETURN ws_slug;
END;
$$;

CREATE OR REPLACE FUNCTION public.change_member_role(_ws uuid, _member uuid, _role text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in first';
  END IF;
  IF public.workspace_role(_ws) NOT IN ('owner', 'admin') THEN
    RAISE EXCEPTION 'Only owners and admins can change roles';
  END IF;
  IF _role NOT IN ('admin', 'member', 'viewer') THEN
    RAISE EXCEPTION 'Choose a valid role';
  END IF;
  IF _member = auth.uid() THEN
    RAISE EXCEPTION 'You cannot change your own role here.';
  END IF;
  IF _member = (SELECT owner_id FROM public.workspaces WHERE id = _ws) THEN
    RAISE EXCEPTION 'The workspace owner''s role cannot be changed.';
  END IF;

  UPDATE public.workspace_members SET role = _role
  WHERE workspace_id = _ws AND user_id = _member;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That person is not on your team.';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.remove_member(_ws uuid, _member uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in first';
  END IF;
  IF public.workspace_role(_ws) NOT IN ('owner', 'admin') THEN
    RAISE EXCEPTION 'Only owners and admins can remove members';
  END IF;
  IF _member = auth.uid() THEN
    RAISE EXCEPTION 'You cannot remove yourself here.';
  END IF;
  IF _member = (SELECT owner_id FROM public.workspaces WHERE id = _ws) THEN
    RAISE EXCEPTION 'The workspace owner cannot be removed.';
  END IF;

  DELETE FROM public.workspace_members
  WHERE workspace_id = _ws AND user_id = _member;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That person is not on your team.';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_invite(_invite_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in first';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.workspace_invites i
    WHERE i.id = _invite_id
      AND public.workspace_role(i.workspace_id) IN ('owner', 'admin')
  ) THEN
    RAISE EXCEPTION 'Only owners and admins can cancel invites';
  END IF;

  DELETE FROM public.workspace_invites WHERE id = _invite_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.create_invite(uuid, text, text) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.accept_invite(text) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.change_member_role(uuid, uuid, text) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.remove_member(uuid, uuid) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.cancel_invite(uuid) FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.create_invite(uuid, text, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.accept_invite(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.change_member_role(uuid, uuid, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.remove_member(uuid, uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.cancel_invite(uuid) TO authenticated;
